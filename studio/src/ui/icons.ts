/**
 * Resolves the most specific Material Design Icon for a node based on its
 * Google Cloud / AWS / Azure / Kubernetes / On-Premises product technology (`tech`)
 * and label, falling back to its category icon (`KIND_ICONS[node.kind]`).
 */
export function resolveNodeIcon(node: Pick<DNode, 'label' | 'kind' | 'tech'>): IconName {
  const t = `${node.label} ${node.tech ?? ''}`.toLowerCase();
  // Gen AI & ML (Google Cloud Vertex AI, AWS Bedrock/SageMaker, Azure OpenAI/AI Foundry)
  if (/\b(document ai|textract|document intelligence|form recognizer|ocr|invoice parser|form parser|claims parser)\b/.test(t)) return 'document_scanner';
  if (/\b(contact center ai|ccai|amazon lex|bot service|customer agent|support agent|voice agent|virtual agent)\b/.test(t)) return 'support_agent';
  if (/\b(agent builder|multi-?agent|autonomous agent|ai agent|agentic|copilot|amazon q|adk)\b/.test(t)) return 'smart_toy';
  if (/\b(vector search|vertex ai search|kendra|ai search|cognitive search|enterprise search|grounding|rag|semantic search)\b/.test(t)) return 'find_in_page';
  if (/\b(model training|automl|vertex ai pipelines|sagemaker|fine-?tun\w*|mlops|feature store|model registry|kubeflow)\b/.test(t)) return 'model_training';
  if (/\b(code assist|code generation|code agent|workstations|github|gitlab|source repos\w*)\b/.test(t)) return 'code';
  // Data Analytics, Lakehouse & Observability
  if (/\b(bigquery|redshift|snowflake|synapse|athena|nl2sql|sql analytics)\b/.test(t)) return 'query_stats';
  if (/\b(dataflow|dataproc|cloud composer|dataform|datastream|dataplex|data fusion|kinesis|emr|glue|data factory|databricks|microsoft fabric|etl|cdc)\b/.test(t)) return 'account_tree';
  if (/\b(looker|quicksight|power ?bi|tableau|cloud monitoring|cloud logging|cloud trace|cloud profiler|cloudwatch|azure monitor|application insights|prometheus|grafana|opentelemetry|observability|telemetry)\b/.test(t)) return 'monitoring';
  // Security, Identity & Compliance
  if (/\b(cloud kms|secret manager|secrets manager|key vault|certificate manager|cmek|hsm)\b/.test(t)) return 'vpn_key';
  if (/\b(cloud iam|identity-aware proxy|iap|identity platform|beyondcorp|cognito|entra ?id|active directory|workload identity|zero ?trust|oauth|oidc)\b/.test(t)) return 'policy';
  if (/\b(model armor|guardrails|safety filter|dlp|macie|assured workloads|compliance)\b/.test(t)) return 'verified_user';
  if (/\b(cloud armor|security command center|chronicle|secops|aws waf|aws shield|guardduty|security hub|sentinel|defender|waf|ddos|siem)\b/.test(t)) return 'security';
  // DevOps & CI/CD
  if (/\b(cloud build|codebuild|codepipeline|azure devops|ci\/?cd|build pipeline)\b/.test(t)) return 'build';
  if (/\b(cloud deploy|codedeploy|argocd|flux|helm|release)\b/.test(t)) return 'rocket_launch';
  // Networking & Edge
  if (/\b(cloud dns|route ?53|azure dns|coredns)\b/.test(t)) return 'dns';
  if (/\b(cloud cdn|cloudfront|front door|global accelerator)\b/.test(t)) return 'public';
  if (/\b(cloud vpn|cloud interconnect|direct connect|transit gateway|expressroute|virtual wan|cloud nat|private service connect|service mesh|istio)\b/.test(t)) return 'lan';
  // Compute, Containers & Storage
  if (/\b(gke|google kubernetes engine|eks|aks|kubernetes|k8s|openshift|istio|pod|statefulset)\b/.test(t)) return 'view_in_ar';
  if (/\b(compute engine|ec2|azure vm|virtual machine|vmware engine|bare metal|mainframe)\b/.test(t)) return 'memory';
  if (/\b(cloud storage|s3|blob storage|adls|filestore|efs|ebs|fsx|glacier|hyperdisk|persistent disk|artifact registry|ecr|acr|gcs)\b/.test(t)) return 'storage';
  if (/\b(bigtable|spanner|alloydb|dynamodb|cosmos ?db|aurora|cockroach\w*|cassandra)\b/.test(t)) return 'dataset';
  // Industry & Domain nodes
  if (/\b(iot|sensor|telemetry device|edge device)\b/.test(t)) return 'sensors';
  if (/\b(on-?prem\w*|data ?center|corporate network|branch office)\b/.test(t)) return 'domain';
  if (/\b(factory|manufacturing|scada|plc|supply chain)\b/.test(t)) return 'factory';
  if (/\b(payment|billing|stripe|checkout|fraud|finops)\b/.test(t)) return 'payments';
  if (/\b(ehr|fhir|clinical|patient|healthcare|hl7)\b/.test(t)) return 'vital_signs';
  return KIND_ICONS[node.kind];
}
